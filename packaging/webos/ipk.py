#!/usr/bin/env python3
"""Harden and verify the TV packages.

  ipk.py elf [--gstreamer] BINARY...
                         ARMv7 EABI5 soft-float, stripped, only TV libraries
                         (--gstreamer: also the TV's GStreamer and GLib, for
                         the slim worker's hardware H.264 encoder)
  ipk.py secure PACKAGE  normalize ownership and modes, reject stray payload
  ipk.py verify PACKAGE  check a hardened package without changing it
  ipk.py appinfo VERSION_FILE SOURCE DEST
                         write SOURCE's appinfo.json to DEST with the app
                         version derived from the product version; print it

Both flavours install the same paths (app io.prysm.tv, service
io.prysm.tv.service), so one allowlist covers both.
"""
import io
import json
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile
import tempfile

APP_ID = 'io.prysm.tv'
SERVICE_ID = APP_ID + '.service'
APP = f'usr/palm/applications/{APP_ID}/'
SERVICE = f'usr/palm/services/{SERVICE_ID}/'
PACKAGE_INFO = f'usr/palm/packages/{APP_ID}/packageinfo.json'
ROOTS = (APP.rstrip('/'), SERVICE.rstrip('/'), PACKAGE_INFO.rsplit('/', 1)[0])
EXECUTABLES = {SERVICE + name for name in ('setup.sh', 'prysm-webos-service', 'prysm-webos-worker')}
SERVICE_FILES = EXECUTABLES | {SERVICE + name for name in (
    'services.json',
    'supervisor.role.json',
    'worker.role.json',
    'supervisor.service',
    'supervisor.client.json',
    'supervisor.api.json',
    'licenses/prysm.txt',
    'licenses/hyperion.txt',
    'licenses/tv-native-apis.txt',
    # Generated by the frontend build from the packages its bundles contain.
    'licenses/javascript.txt',
)}
# The slim package's H.264 encoders: OpenH264 (compiled in) and the GStreamer
# and GLib Rust bindings. Allowed in either flavour, required in neither.
OPTIONAL_SERVICE_FILES = {SERVICE + name for name in (
    'licenses/openh264.txt',
    'licenses/gstreamer-rs.txt',
    'licenses/gtk-rs.txt',
)}
APP_REQUIRED = {APP + name for name in ('appinfo.json', 'index.html', 'icon.png')}
MEMBERS = ['debian-binary', 'control.tar.gz', 'data.tar.gz']

# What the TV (webOS 10, 32-bit userland, glibc 2.12) provides to these binaries.
LIBRARIES = {
    'ld-linux.so.3', 'libc.so.6', 'libm.so.6', 'libdl.so.2', 'libpthread.so.0',
    'librt.so.1', 'libgcc_s.so.1', 'libstdc++.so.6',
}
# The TV's GStreamer 1.0 and GLib, which the hardware H.264 encoder (rvenc) runs on.
GSTREAMER_LIBRARIES = {
    'libglib-2.0.so.0', 'libgobject-2.0.so.0', 'libgstreamer-1.0.so.0',
    'libgstapp-1.0.so.0', 'libgstvideo-1.0.so.0', 'libgstallocators-1.0.so.0',
    'libgstbase-1.0.so.0',
}
# Highest symbol version per library family; raise only after checking a TV.
# CXXABI 1.3.9 (sized operator delete, from OpenH264's C++ in the slim worker):
# the old io.prysm.capture worker needed the same and ran OpenH264 on the TV.
VERSIONS = {'GLIBC': (2, 12), 'GLIBCXX': (3, 4), 'CXXABI': (1, 3, 9), 'GCC': (4, 3, 0)}


def product_version(version_file):
    """The product version: the one line of the repository's VERSION file."""
    version = Path(version_file).read_text().strip()
    if not version or any(c.isspace() for c in version):
        raise ValueError(f'{version_file} must hold one version')
    return version


def app_version(version):
    """The appinfo.json version for a product version: its major.minor.patch.

    ares-package accepts only three dot-separated numbers, so a pre-release or
    build suffix (1.0.0-alpha.0) is dropped; the binaries report the full version.
    """
    match = re.fullmatch(r'((?:0|[1-9]\d{0,8})\.(?:0|[1-9]\d{0,8})\.(?:0|[1-9]\d{0,8}))(?:[-+].*)?', version)
    if not match:
        raise ValueError('unexpected product version: ' + version)
    return match.group(1)


def write_appinfo(version_file, source, destination):
    """Copy appinfo.json with the version from VERSION; return that version."""
    appinfo = json.loads(Path(source).read_text())
    if 'version' in appinfo:
        raise ValueError(f'{source} must not set version; it comes from VERSION')
    version = app_version(product_version(version_file))
    appinfo = {'id': appinfo.pop('id'), 'version': version, **appinfo}
    Path(destination).write_text(json.dumps(appinfo, indent=2) + '\n')
    return version


def write_ar(destination, members):
    with Path(destination).open('wb') as output:
        output.write(b'!<arch>\n')
        for name, data in members.items():
            if len(name) > 15:
                raise ValueError('IPK member name is too long')
            header = f'{name:<16}{0:<12}{0:<6}{0:<6}{"100644":<8}{len(data):<10}`\n'
            output.write(header.encode('ascii'))
            output.write(data)
            if len(data) % 2:
                output.write(b'\n')


def read_ar(package):
    data = Path(package).read_bytes()
    if not data.startswith(b'!<arch>\n'):
        raise ValueError('not an ar archive')
    members, offset = {}, 8
    while offset < len(data):
        header = data[offset:offset + 60]
        if len(header) != 60 or header[58:60] != b'`\n':
            raise ValueError('truncated ar header')
        name = header[:16].decode('ascii').strip().rstrip('/')
        size = int(header[48:58].decode('ascii').strip())
        offset += 60
        members[name] = data[offset:offset + size]
        offset += size + (size % 2)
    if list(members) != MEMBERS:
        raise ValueError('expected an unsigned webOS IPK with exactly ' + ', '.join(MEMBERS))
    return members


def normalized_name(member):
    name = member.name.removeprefix('./').rstrip('/')
    return '' if name == '.' else name


def allowed(name, is_dir):
    return any(name == root or name.startswith(root + '/') or
               (is_dir and root.startswith(name + '/')) for root in ROOTS)


def check_member(archive, member):
    name = normalized_name(member)
    if not (member.isdir() or member.isfile()):
        raise ValueError('unexpected link or special file: ' + member.name)
    if archive == 'control.tar.gz':
        if name not in ('', 'control'):
            raise ValueError('installation scripts are not allowed in the Prysm IPK: ' + member.name)
        return name
    if name == '':
        if not member.isdir():
            raise ValueError('unexpected package root')
        return name
    if member.name.startswith('/') or any(part in ('', '.', '..') for part in name.split('/')):
        raise ValueError('unexpected package path: ' + member.name)
    if not allowed(name, member.isdir()):
        raise ValueError('unexpected package path: ' + member.name)
    if member.isfile() and name.startswith(SERVICE) and name not in SERVICE_FILES | OPTIONAL_SERVICE_FILES:
        raise ValueError('unexpected service file: ' + name)
    return name


def expected_mode(name, member):
    return 0o755 if member.isdir() or name in EXECUTABLES else 0o644


def check_payload(files):
    missing = sorted((SERVICE_FILES | APP_REQUIRED | {PACKAGE_INFO}) - files)
    if missing:
        raise ValueError('missing package files: ' + ', '.join(missing))


def secure(package):
    """Rewrite the package with root ownership and fixed modes; validate paths."""
    package = Path(package).resolve()
    members = read_ar(package)
    files = set()
    for archive in MEMBERS[1:]:
        output = io.BytesIO()
        with tarfile.open(fileobj=io.BytesIO(members[archive]), mode='r:gz') as old, \
                tarfile.open(fileobj=output, mode='w:gz', format=tarfile.GNU_FORMAT) as new:
            for member in old.getmembers():
                name = check_member(archive, member)
                if archive == 'data.tar.gz' and member.isfile():
                    if name in files:
                        raise ValueError('duplicate package file: ' + name)
                    files.add(name)
                member.mode = expected_mode(name, member)
                member.uid = member.gid = 0
                member.uname = member.gname = 'root'
                new.addfile(member, old.extractfile(member) if member.isfile() else None)
        members[archive] = output.getvalue()
    check_payload(files)
    with tempfile.NamedTemporaryFile(dir=package.parent, delete=False) as temporary:
        pass
    try:
        write_ar(temporary.name, members)
        os.chmod(temporary.name, 0o644)
        os.replace(temporary.name, package)
    finally:
        Path(temporary.name).unlink(missing_ok=True)


def verify(package):
    """Check a hardened package; return its data listing as (mode, size, name)."""
    members = read_ar(package)
    if members['debian-binary'] != b'2.0\n':
        raise ValueError('unexpected debian-binary')
    listing, files = [], set()
    for archive in MEMBERS[1:]:
        with tarfile.open(fileobj=io.BytesIO(members[archive]), mode='r:gz') as tar:
            for member in tar.getmembers():
                name = check_member(archive, member)
                if member.mode != expected_mode(name, member) or member.uid or member.gid:
                    raise ValueError(f'unexpected owner or mode {member.mode:o}: {member.name}')
                if archive == 'data.tar.gz':
                    listing.append((member.mode, member.size, name + ('/' if member.isdir() else '')))
                    if member.isfile():
                        files.add(name)
    check_payload(files)
    return listing


def readelf(*args):
    sdk = os.environ.get('WEBOS_SDK')
    if not sdk:
        raise SystemExit('Set WEBOS_SDK to use the SDK readelf')
    tool = Path(sdk) / 'bin/arm-webos-linux-gnueabi-readelf'
    return subprocess.run([str(tool), '-W', *args], check=True, capture_output=True, text=True).stdout


def version_tuple(text):
    return tuple(int(part) for part in text.split('.'))


def check_elf(binary, gstreamer=False):
    """Raise unless `binary` is a stripped ARMv7 soft-float EABI5 executable for the TV."""
    header = readelf('-h', binary)
    for expected in ('ELF32', 'ARM', 'Version5 EABI', 'soft-float ABI'):
        if expected not in header:
            raise ValueError(f'{binary}: not an ARM EABI5 soft-float ELF32 ({expected} missing)')
    attributes = readelf('-A', binary)
    if 'Tag_ABI_VFP_args: VFP registers' in attributes:
        raise ValueError(f'{binary}: uses the hard-float calling convention')
    program = readelf('-l', binary)
    if '[Requesting program interpreter: /lib/ld-linux.so.3]' not in program:
        raise ValueError(f'{binary}: unexpected program interpreter')
    sections = readelf('-S', binary)
    debug = sorted(set(re.findall(r'\s(\.(?:debug_\w+|symtab|strtab))\s', sections)))
    if debug:
        raise ValueError(f'{binary}: not stripped: {", ".join(debug)}')
    needed = set(re.findall(r'\(NEEDED\)\s+Shared library: \[(.+?)\]', readelf('-d', binary)))
    unknown = sorted(needed - LIBRARIES - (GSTREAMER_LIBRARIES if gstreamer else set()))
    if unknown:
        raise ValueError(f'{binary}: needs libraries the TV may lack: {", ".join(unknown)}')
    highest = {}
    for family, version in re.findall(r'\b(GLIBC|GLIBCXX|CXXABI|GCC)_([0-9.]+)\b', readelf('-V', binary)):
        if version_tuple(version) > version_tuple('.'.join(map(str, highest.get(family, (0,))))):
            highest[family] = version_tuple(version)
    for family, version in highest.items():
        if version > VERSIONS[family]:
            raise ValueError(f'{binary}: needs {family}_{".".join(map(str, version))}, '
                             f'above the TV baseline {".".join(map(str, VERSIONS[family]))}')
    return sorted(needed), {family: '.'.join(map(str, v)) for family, v in sorted(highest.items())}


def main(argv):
    if len(argv) >= 2 and argv[0] == 'elf':
        gstreamer = argv[1] == '--gstreamer'
        binaries = argv[2:] if gstreamer else argv[1:]
        if not binaries:
            raise SystemExit(__doc__)
        for binary in binaries:
            needed, versions = check_elf(binary, gstreamer)
            print(f'{binary}: ok; needs {" ".join(needed)}; '
                  + ' '.join(f'{family}_{version}' for family, version in versions.items()))
        return
    if len(argv) == 2 and argv[0] == 'secure':
        secure(argv[1])
        return
    if len(argv) == 4 and argv[0] == 'appinfo':
        print(write_appinfo(*argv[1:]))
        return
    if len(argv) == 2 and argv[0] == 'verify':
        for mode, size, name in verify(argv[1]):
            print(f'{mode:04o} {size:>9} {name}')
        return
    raise SystemExit(__doc__)


if __name__ == '__main__':
    try:
        main(sys.argv[1:])
    except ValueError as error:
        raise SystemExit(f'ipk.py: {error}') from None
