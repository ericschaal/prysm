// The TV's type guards and their declarations come from the same reply schemas.
import { readFileSync } from 'node:fs';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import openapiTS, { astToString } from 'openapi-typescript';

const document = JSON.parse(readFileSync(0, 'utf8'));
const schemas = document.components.schemas;
const guards = {
  isStatus: 'StatusReply',
  isErrorReply: 'FailureReply',
  isExecReply: 'HomebrewExecReply',
};
for (const [name, base, returnValue] of [
  ['StatusReply', 'ServiceStatus', true],
  ['FailureReply', 'ErrorReply', false],
]) {
  schemas[name] = {
    allOf: [
      { $ref: `#/components/schemas/${base}` },
      {
        type: 'object',
        required: ['returnValue'],
        properties: { returnValue: { type: 'boolean', const: returnValue } },
      },
    ],
  };
}
// Homebrew owns exec. Only describe the fields used by the setup screen.
schemas.HomebrewExecReply = {
  type: 'object',
  required: ['returnValue'],
  properties: {
    returnValue: { type: 'boolean' },
    errorText: { type: 'string' },
    stderrString: { type: 'string' },
  },
};

process.stdout.write('/** Generated by cargo xtask codegen. Do not edit. */\n');
if (process.argv[2] === 'types') {
  process.stdout.write(astToString(await openapiTS(document)));
  for (const [guard, schema] of Object.entries(guards)) {
    process.stdout.write(
      `export function ${guard}(value: unknown): value is components["schemas"]["${schema}"];\n`,
    );
  }
} else {
  // JSON.parse can only preserve consecutive integer values through MAX_SAFE_INTEGER.
  for (const field of Object.values(schemas.Observation.properties)) {
    if (field.format === 'uint32') field.maximum = 2 ** 32 - 1;
    if (field.format === 'uint64') field.maximum = Number.MAX_SAFE_INTEGER;
  }
  const ajv = new Ajv2020({
    code: { source: true, esm: true, lines: true },
    formats: { uint32: true, uint64: true },
    messages: false,
  });
  ajv.addKeyword('components');
  const id = 'urn:prysm:service';
  ajv.addSchema({ components: document.components }, id);
  const refs = Object.fromEntries(
    Object.entries(guards).map(([guard, schema]) => [
      guard,
      `${id}#/components/schemas/${schema}`,
    ]),
  );
  process.stdout.write(standalone.default(ajv, refs));
}
