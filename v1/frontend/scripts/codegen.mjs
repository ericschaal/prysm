import { execFileSync } from 'node:child_process';
import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const banner = '/** Generated by npm run codegen from Rust. Do not edit. */\n';

export async function updateGeneratedFiles(directory, files, check) {
  const existing = await readdir(directory).catch((error) => {
    if (error.code === 'ENOENT') return [];
    throw error;
  });
  const stale = existing.filter((name) => !Object.hasOwn(files, name));
  for (const [name, content] of Object.entries(files)) {
    const previous = await readFile(resolve(directory, name), 'utf8').catch(
      (error) => {
        if (error.code === 'ENOENT') return null;
        throw error;
      },
    );
    if (previous !== content) stale.push(name);
  }
  if (check) {
    if (stale.length)
      throw new Error(
        `Generated contracts differ: ${stale.join(', ')}. Run npm --prefix v1/frontend run codegen.`,
      );
    return;
  }
  await mkdir(directory, { recursive: true });
  for (const name of existing.filter((name) => !Object.hasOwn(files, name))) {
    await unlink(resolve(directory, name));
  }
  for (const [name, content] of Object.entries(files)) {
    await writeFile(resolve(directory, name), content);
  }
}

/** Mechanically translate named documents; no adapter names or type mappings. */
export async function renderDocuments(documents) {
  const files = {
    'manifest.json':
      JSON.stringify(Object.keys(documents).sort(), null, 2) + '\n',
  };
  for (const [name, document] of Object.entries(documents).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    if (!/^[a-z][a-z0-9-]*$/.test(name))
      throw new Error(`Invalid contract module name: ${name}`);
    files[`${name}.openapi.json`] = JSON.stringify(document, null, 2) + '\n';
    files[`${name}.generated.ts`] =
      banner +
      astToString(
        await openapiTS(document, {
          rootTypes: true,
          rootTypesNoSchemaPrefix: true,
          rootTypesKeepCasing: true,
          // Settings are request bodies: a field serde defaults may be omitted.
          defaultNonNullable: false,
        }),
      );
  }
  return files;
}

async function generate(check) {
  const cargoArgs = [
    'run',
    '--quiet',
    '--manifest-path',
    resolve(root, '../Cargo.toml'),
    '--locked',
    '-p',
    'prysm-export-contracts',
  ];
  const run = (args) =>
    execFileSync('cargo', args, {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'inherit'],
    });
  const documents = JSON.parse(run(cargoArgs));
  const files = await renderDocuments(documents);
  files['fixtures.json'] =
    JSON.stringify(
      JSON.parse(run([...cargoArgs, '--', '--fixtures'])),
      null,
      2,
    ) + '\n';
  await updateGeneratedFiles(
    resolve(root, 'packages/contracts/generated'),
    files,
    check,
  );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check'))
    throw new Error('Usage: codegen.mjs [--check]');
  await generate(args.includes('--check'));
}
